-- Bwalo: African sports platform. D1 database, bound as DB.
CREATE TABLE IF NOT EXISTS users(
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  pass TEXT NOT NULL, salt TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'user',
  status TEXT NOT NULL DEFAULT 'active', totp TEXT, prefs TEXT, created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, uid TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS docs(
  col TEXT NOT NULL, id TEXT NOT NULL, lid TEXT, data TEXT NOT NULL,
  seq INTEGER NOT NULL, deleted INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(col,id));
CREATE INDEX IF NOT EXISTS docs_seq ON docs(seq);
CREATE INDEX IF NOT EXISTS docs_lid ON docs(lid);
CREATE TABLE IF NOT EXISTS meta(k TEXT PRIMARY KEY, v TEXT NOT NULL);
INSERT OR IGNORE INTO meta(k,v) VALUES('seq','0');
CREATE TABLE IF NOT EXISTS attempts(k TEXT NOT NULL, at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS attempts_k ON attempts(k,at);
CREATE TABLE IF NOT EXISTS clicks(id TEXT PRIMARY KEY, n INTEGER NOT NULL DEFAULT 0);
